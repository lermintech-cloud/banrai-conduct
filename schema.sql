CREATE TABLE IF NOT EXISTS cfg(key TEXT PRIMARY KEY,value TEXT);
CREATE TABLE IF NOT EXISTS students(id TEXT PRIMARY KEY,code TEXT,name TEXT NOT NULL,cls TEXT);
CREATE TABLE IF NOT EXISTS records(id TEXT PRIMARY KEY,sid TEXT NOT NULL,d TEXT,ty TEXT,lv INTEGER,item TEXT,pts INTEGER,note TEXT,who TEXT,created TEXT DEFAULT (datetime('now')));
CREATE INDEX IF NOT EXISTS ix_rec_sid ON records(sid);
